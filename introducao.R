# Introdução ao RStudio e as Variáveis

# Para executar os comandos: ctrl + Enter. 
# Também é possível selecionar um conjunto de linhas e executar todas juntas

# Para limpar o console: ctrl + L

# Para atribuir funções: operador de igualdade =

# Para declarar variáveis: operador seta para esquerda <-
# Exemplos:

a <- 10
b <- 10
c <- a + b

print(c)

# Strings:

mensagem <- "Hello, World!"
print(mensagem)